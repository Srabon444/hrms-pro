import { expect, test, type Page } from '@playwright/test';
import { caption, pause, scrollThrough, signIn, signOut } from './helpers';

const LEAVE_DAY = process.env.WALK_LEAVE_DAY ?? '2026-12-14';

async function go(page: Page, label: string) {
	await page.locator('#main-nav').getByRole('link', { name: label, exact: true }).click();
	await page.waitForLoadState('load');
}

async function visit(page: Page, label: string, title: string, detail: string, steps = 2) {
	await go(page, label);
	await caption(page, title, detail);
	await scrollThrough(page, steps);
}

test('product walkthrough', async ({ page }) => {
	await page.goto('/login');
	await caption(page, 'HRMS Pro', 'A multi-tenant HR system for a software company. Demo tenant: Nimbus Labs Ltd.');

	await signIn(page, 'owner@demo.local');
	await caption(page, 'Owner home', 'Headcount, pending approvals, payroll and who is out today, all scoped by role.');
	await scrollThrough(page);

	await visit(
		page,
		'Employees',
		'Employee directory',
		'Search, filter, CSV import and export. Every row is tenant-isolated by Postgres RLS.',
		1
	);
	await page.locator('table a').first().click();
	await page.waitForLoadState('load');
	await caption(page, 'Employee profile', 'Job, pay, documents, history and an audit trail of every change.');
	await scrollThrough(page, 3);

	await visit(page, 'Organisation', 'Organisation', 'Departments, designations, grades and branches.');

	await go(page, 'Settings');
	await caption(page, 'Settings hub', 'Every rule the company runs on, grouped and permission-gated.');
	await page.getByRole('link', { name: 'Roles' }).first().click();
	await page.waitForLoadState('load');
	await caption(
		page,
		'Role-based access',
		'178 permissions, each granted at own, team, department or whole-company scope.'
	);
	await scrollThrough(page, 3);
	await signOut(page);

	await signIn(page, 'staff@demo.local');
	await caption(page, 'Staff view', 'Imran, a software engineer, sees only his own work and data.');
	await go(page, 'Leave');
	await caption(page, 'Request leave', 'Balances come from accrual rules. Weekends and holidays are skipped.');
	await page.getByRole('combobox', { name: 'Leave type' }).selectOption({ index: 0 });
	await page.getByRole('textbox', { name: 'From', exact: true }).fill(LEAVE_DAY);
	await page.getByRole('textbox', { name: 'To', exact: true }).fill(LEAVE_DAY);
	await page
		.getByRole('textbox', { name: 'Reason', exact: true })
		.pressSequentially('Doctor appointment', { delay: 50 });
	await pause(page, 800);
	await page.getByRole('button', { name: 'Request leave' }).click();
	await page.waitForLoadState('load');
	await expect(page.getByText('Leave requested.')).toBeVisible();
	await caption(page, 'Request sent', 'The approver gets an in-app notification and an email.');

	await visit(page, 'Attendance', 'Attendance', 'Punch in and out, monthly summary and correction requests.');
	await visit(page, 'Meals', 'Meals', 'Order lunch by cut-off. The month-end bill is emailed to each employee.');
	await visit(page, 'My payslips', 'My payslips', 'Approved payslips with a downloadable PDF.', 1);
	await visit(page, 'Expenses', 'Expense claims', 'Submit claims with receipts stored in MinIO.', 1);
	await signOut(page);

	await signIn(page, 'hr@demo.local');
	await go(page, 'Approvals');
	await caption(page, 'Approvals inbox', 'HR sees every pending request it is allowed to act on.');
	await page
		.getByRole('link', { name: /Imran Hossain/ })
		.first()
		.click();
	await page.waitForLoadState('load');
	await caption(page, 'Review the request', 'Days counted, skipping weekends and holidays, and the remaining balance.');
	await page.getByRole('button', { name: 'Approve' }).click();
	await page.waitForLoadState('load');
	await caption(page, 'Approved', 'Balance is deducted and the employee is notified.');
	await signOut(page);

	await signIn(page, 'owner@demo.local');
	await go(page, 'Payroll');
	await caption(
		page,
		'Payroll',
		'Monthly runs with tax, provident fund, loans and overtime. Draft, approve, then publish payslips.'
	);
	await page.locator('a[href*="payroll?run="]').first().click();
	await page.waitForLoadState('load');
	await scrollThrough(page, 3);
	await visit(
		page,
		'Salaries',
		'Salary structures',
		'Basic, allowances and revisions per employee. Money is stored as integer poisha.'
	);
	await visit(page, 'Meal bills', 'Meal bills', 'Generated by a background worker and emailed through BullMQ.');
	await visit(page, 'Recruitment', 'Recruitment', 'Openings, candidates, interview loops and feedback.');
	await visit(page, 'Performance', 'Performance', 'Review cycles, goals, self and manager ratings.');
	await visit(page, 'Assets', 'Assets', 'Laptops and devices, who holds what, and returns on exit.');
	await visit(page, 'Helpdesk', 'Helpdesk', 'Tickets to HR, IT or admin, with confidential categories.');
	await visit(page, 'Announcements', 'Announcements', 'Company news, pinned and scheduled.');
	await visit(page, 'Reports', 'Reports', 'Headcount, leave, attendance and payroll reports with CSV export.');
	await go(page, 'Settings');
	await page.getByRole('link', { name: 'Audit log' }).first().click();
	await page.waitForLoadState('load');
	await caption(page, 'Audit log', 'Database triggers record every change. Sensitive fields are masked.');
	await scrollThrough(page, 2);

	await page.setViewportSize({ width: 390, height: 844 });
	await page.goto(page.url().replace(/\/settings\/audit.*/, ''));
	await caption(page, 'Fully responsive', 'The same app on a phone.');
	await page.getByRole('button', { name: 'Menu' }).click();
	await pause(page, 1500);
	await page.getByRole('button', { name: 'Close' }).click();
	await scrollThrough(page, 3);
	await page.setViewportSize({ width: 1440, height: 900 });
	await caption(
		page,
		'HRMS Pro',
		'SvelteKit, Postgres RLS, Redis, BullMQ, MinIO, Docker. 600+ unit, integration and e2e tests.'
	);
	await pause(page, 2500);
});
